import fs from 'fs';

const FIXTURES_DIR = 'apps/agent/fixtures';
const OUT_DIR = 'apps/agent/eval-report';

const files = fs.readdirSync(FIXTURES_DIR).filter((f) => f.endsWith('.json'));

const sections = files
  .map((file) => {
    const data = JSON.parse(fs.readFileSync(`${FIXTURES_DIR}/${file}`, 'utf8'));
    const rows = (data.fixtures ?? [])
      .map(
        (f) => `
      <tr>
        <td><code>${JSON.stringify(f.match)}</code></td>
        <td><pre>${JSON.stringify(f.response, null, 2).slice(0, 400)}…</pre></td>
      </tr>`,
      )
      .join('');
    return `
    <h2>${file} <span class="count">${(data.fixtures ?? []).length} fixture${(data.fixtures ?? []).length !== 1 ? 's' : ''}</span></h2>
    <table>
      <thead><tr><th>Match</th><th>Response (preview)</th></tr></thead>
      <tbody>${rows}</tbody>
    </table>`;
  })
  .join('\n');

const totalFixtures = files.reduce((sum, file) => {
  const data = JSON.parse(fs.readFileSync(`${FIXTURES_DIR}/${file}`, 'utf8'));
  return sum + (data.fixtures ?? []).length;
}, 0);

const html = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <title>AIMock Fixtures — Travel Assistant</title>
  <style>
    body    { font-family: system-ui, sans-serif; max-width: 960px; margin: 40px auto; padding: 0 20px; color: #222; }
    h1      { border-bottom: 2px solid #0070f3; padding-bottom: 8px; }
    h2      { color: #0070f3; margin-top: 32px; }
    table   { width: 100%; border-collapse: collapse; margin-bottom: 24px; }
    th      { background: #f0f4ff; text-align: left; padding: 8px; border: 1px solid #ddd; }
    td      { padding: 8px; vertical-align: top; border: 1px solid #ddd; font-size: 13px; }
    pre     { margin: 0; white-space: pre-wrap; word-break: break-all; font-size: 11px; }
    code    { background: #f5f5f5; padding: 2px 4px; border-radius: 3px; }
    .badge  { display: inline-block; padding: 2px 10px; border-radius: 12px; font-size: 12px; font-weight: 600; background: #d1fae5; color: #065f46; }
    .count  { font-size: 13px; font-weight: normal; color: #666; margin-left: 8px; }
    nav     { margin-bottom: 24px; }
    nav a   { margin-right: 16px; color: #0070f3; text-decoration: none; font-weight: 500; }
    nav a:hover { text-decoration: underline; }
  </style>
</head>
<body>
  <nav>
    <a href="index.html">← Evalite Report</a>
    <a href="aimock.html">AIMock Fixtures</a>
  </nav>
  <h1>AIMock Fixtures <span class="badge">mock mode</span></h1>
  <p>
    Loaded from <code>apps/agent/fixtures/</code> via <code>loadFixtureDir()</code>.
    ${files.length} file${files.length !== 1 ? 's' : ''}, ${totalFixtures} fixture${totalFixtures !== 1 ? 's' : ''} total.
    No real API calls — zero cost, fully reproducible.
  </p>
  ${sections}
  <hr style="margin-top: 40px">
  <p style="color: #888; font-size: 12px">Generated by GitHub Actions · ${new Date().toISOString()}</p>
</body>
</html>`;

fs.mkdirSync(OUT_DIR, { recursive: true });
fs.writeFileSync(`${OUT_DIR}/aimock.html`, html.trim());
console.log(`✓ aimock.html written (${files.length} files, ${totalFixtures} fixtures)`);
